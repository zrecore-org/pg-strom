#!/bin/sh
# gen_ksrc.sh OUT_C OUT_H file1 file2 ...
# Embeds the kernel sources (the .slang and .inc files of kernels_vm/) as a table
#   ksrc_files[] = { name (the file's base name), data, length }
# so that the service can recompile specialized kernels at run time (specialize.c). Uses only od and awk.
out_c=$1; out_h=$2; shift 2
{
	printf '/* generated by gen_ksrc.sh - do not edit */\n#ifndef KERNELS_SRC_H\n#define KERNELS_SRC_H\n'
	printf 'typedef struct ksrc_file\n{\n\tconst char *name;\n\tconst unsigned char *data;\n\tunsigned int len;\n} ksrc_file;\n'
	printf 'extern const ksrc_file ksrc_files[];\nextern const unsigned int ksrc_nfiles;\n#endif\n'
} > "$out_h.tmp" || exit 1
{
	printf '/* generated by gen_ksrc.sh - do not edit */\n#include "kernels_src.h"\n'
	i=0
	for f in "$@"; do
		printf 'static const unsigned char ksrc_data_%d[] = {\n' "$i"
		od -An -v -t x1 "$f" | awk '{ s = ""; for (i = 1; i <= NF; i++) s = s "0x" $i ","; print s }'
		printf '0};\n'
		i=$((i+1))
	done
	printf 'const ksrc_file ksrc_files[] = {\n'
	i=0
	for f in "$@"; do
		sz=$(wc -c < "$f" | tr -d ' ')
		printf '\t{ "%s", ksrc_data_%d, %s },\n' "$(basename "$f")" "$i" "$sz"
		i=$((i+1))
	done
	printf '};\nconst unsigned int ksrc_nfiles = %d;\n' "$i"
} > "$out_c.tmp" || exit 1
mv "$out_c.tmp" "$out_c" && mv "$out_h.tmp" "$out_h"
