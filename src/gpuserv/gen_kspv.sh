#!/bin/sh
# gen_kspv.sh OUT_C OUT_H file1.spv file2.spv ...
# Embeds SPIR-V binaries as 'const unsigned char kspv_<name>[]' (4-byte aligned) plus
# 'const unsigned int kspv_<name>_len' (bytes). Uses only od and awk (no xxd needed).
out_c=$1; out_h=$2; shift 2
{
	printf '/* generated by gen_kspv.sh - do not edit */\n#ifndef KERNELS_SPV_H\n#define KERNELS_SPV_H\n'
	for f in "$@"; do
		n=$(basename "$f" .spv)
		printf 'extern const unsigned char kspv_%s[];\nextern const unsigned int kspv_%s_len;\n' "$n" "$n"
	done
	printf '#endif\n'
} > "$out_h.tmp" || exit 1
{
	printf '/* generated by gen_kspv.sh - do not edit */\n#include "kernels_spv.h"\n'
	for f in "$@"; do
		n=$(basename "$f" .spv)
		sz=$(wc -c < "$f" | tr -d ' ')
		printf 'const unsigned char kspv_%s[] __attribute__((aligned(4))) = {\n' "$n"
		od -An -v -t x1 "$f" | awk '{ s = ""; for (i = 1; i <= NF; i++) s = s "0x" $i ","; print s }'
		printf '};\nconst unsigned int kspv_%s_len = %s;\n' "$n" "$sz"
	done
} > "$out_c.tmp" || exit 1
mv "$out_c.tmp" "$out_c" && mv "$out_h.tmp" "$out_h"
