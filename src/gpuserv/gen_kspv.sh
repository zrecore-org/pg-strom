#!/bin/sh
# gen_kspv.sh OUT_C OUT_H file1.spv file2.spv ...
# Embeds SPIR-V binaries as 'const unsigned char kspv_<name>[]' (4-byte aligned) plus 'const unsigned int kspv_<name>_len' (bytes).
# The bytes are not turned into C source: that made kernels_spv.c several GB (Clang stops at 2 GB of source locations, and the full and
# the lite kernels together are more than 400 MB of SPIR-V) and slow to compile. Each file is pulled in by the assembler (.incbin) from
# a top-level asm statement, which defines the symbol; the length is a plain C constant. The paths are those given on the command line,
# relative to the directory the compiler runs in (src/gpuserv).
out_c=$1; out_h=$2; shift 2
{
	printf '/* generated by gen_kspv.sh - do not edit */\n#ifndef KERNELS_SPV_H\n#define KERNELS_SPV_H\n'
	for f in "$@"; do
		n=$(basename "$f" .spv)
		printf 'extern const unsigned char kspv_%s[];\nextern const unsigned int kspv_%s_len;\n' "$n" "$n"
	done
	printf '#endif\n'
} > "$out_h.tmp" || exit 1
{
	printf '/* generated by gen_kspv.sh - do not edit */\n#include "kernels_spv.h"\n'
	printf '#if defined(__APPLE__)\n'
	printf '#define KSPV_ASM(name, path) __asm__(".section __DATA,__const\\n.globl _kspv_" #name "\\n.p2align 2\\n_kspv_" #name ":\\n.incbin \\"" path "\\"\\n.text\\n")\n'
	printf '#else\n'
	printf '#define KSPV_ASM(name, path) __asm__(".section .rodata\\n.globl kspv_" #name "\\n.balign 4\\nkspv_" #name ":\\n.incbin \\"" path "\\"\\n.text\\n")\n'
	printf '#endif\n'
	for f in "$@"; do
		n=$(basename "$f" .spv)
		sz=$(wc -c < "$f" | tr -d ' ')
		printf 'KSPV_ASM(%s, "%s");\nconst unsigned int kspv_%s_len = %s;\n' "$n" "$f" "$n" "$sz"
	done
} > "$out_c.tmp" || exit 1
mv "$out_c.tmp" "$out_c" && mv "$out_h.tmp" "$out_h"
