#!/bin/sh
# gen_kreg.sh OUT.inc file1.spv file2.spv ...
# The table of the interpreter kernels the service can prewarm (kprewarm.c): { name, SPIR-V array, length } for every
# kernel of the VM families (scan, aggregation, GROUP BY, group table, join, join aggregation, Arrow twins), in every tier.
# The probe kernels, the VM self-test kernel and GPU-Sort are not listed.
out=$1; shift
{
	printf '/* generated by gen_kreg.sh - do not edit */\n'
	for f in "$@"; do
		n=$(basename "$f" .spv)
		case "$n" in
			gpuscan*|gpuagg*|gagg*|gtab*|gpujoin*|jagg*|jgagg*|gpuarrow*|aagg*|agagg*|agtab*|ajoin*|ajagg*|ajgagg*) ;;
			*) continue;;
		esac
		printf '{ "%s", kspv_%s, &kspv_%s_len },\n' "$n" "$n" "$n"
	done
} > "$out.tmp" && mv "$out.tmp" "$out"
